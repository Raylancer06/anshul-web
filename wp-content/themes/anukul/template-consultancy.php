    document.querySelectorAll('.faq-toggle').forEach(button => {
      button.addEventListener('click', () => {
        const content = button.nextElementSibling;
        const icon = button.querySelector('.icon-arrow');
        const isExpanded = button.getAttribute('aria-expanded') === 'true';

        // Close all other accordions for quiet editorial feel
        document.querySelectorAll('.faq-toggle').forEach(otherBtn => {
          if (otherBtn !== button) {
            otherBtn.setAttribute('aria-expanded', 'false');
            otherBtn.nextElementSibling.classList.add('hidden');
            const otherIcon = otherBtn.querySelector('.icon-arrow');
            if (otherIcon) {
              otherIcon.textContent = 'add';
            }
          }
        });

        // Toggle current item
        if (isExpanded) {
          button.setAttribute('aria-expanded', 'false');
          content.classList.add('hidden');
          if (icon) icon.textContent = 'add';
        } else {
          button.setAttribute('aria-expanded', 'true');
          content.classList.remove('hidden');
          if (icon) icon.textContent = 'remove';
        }
      });
    });
