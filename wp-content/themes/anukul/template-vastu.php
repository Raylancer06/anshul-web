  (function() {
    const accordionContainer = document.getElementById('vastu-faq-accordion');
    if (!accordionContainer) return;

    const toggles = accordionContainer.querySelectorAll('.faq-toggle');
    toggles.forEach(toggle => {
      toggle.addEventListener('click', function() {
        const item = this.parentElement;
        const content = item.querySelector('.faq-content');
        const icon = item.querySelector('.faq-icon');
        const isOpen = content.style.maxHeight && content.style.maxHeight !== '0px';

        // Close all items
        accordionContainer.querySelectorAll('.faq-content').forEach(c => {
          c.style.maxHeight = '0px';
        });
        accordionContainer.querySelectorAll('.faq-icon').forEach(ic => {
          ic.textContent = 'add';
          ic.classList.remove('rotate-45');
        });

        // If it wasn't open, open it
        if (!isOpen) {
          content.style.maxHeight = content.scrollHeight + 'px';
          icon.textContent = 'close';
        }
      });
    });
  })();
</script>

