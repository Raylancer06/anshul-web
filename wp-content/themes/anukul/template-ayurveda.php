<script>
  function toggleFaq(btn) {
    const parent = btn.closest('.faq-item');
    const answer = parent.querySelector('.faq-answer');
    const icon = btn.querySelector('.material-symbols-outlined');
    const isOpen = !answer.classList.contains('hidden');

    // Close all other open items
    document.querySelectorAll('.faq-item .faq-answer').forEach(el => el.classList.add('hidden'));
    document.querySelectorAll('.faq-item .material-symbols-outlined').forEach(el => el.style.transform = 'rotate(0deg)');

    if (!isOpen) {
      answer.classList.remove('hidden');
      icon.style.transform = 'rotate(180deg)';
    }
  }

  // Ensure active nav styling for Ayurveda
  document.addEventListener('DOMContentLoaded', () => {
    const navLinks = document.querySelectorAll('header nav a');
    navLinks.forEach(link => {
      if (link.getAttribute('data-path') === 'ayurveda') {
        link.classList.add('text-primary', 'font-semibold', 'relative', 'after:absolute', 'after:bottom-[-4px]', 'after:left-0', 'after:w-full', 'after:h-[1.5px]', 'after:bg-[#B38A3E]');
        link.classList.remove('text-on-surface-variant');
      }
    });
  });
</script>

