<!-- CLIENT-SIDE SEARCH & FILTER MICRO-INTERACTIONS -->
<script>
  (function() {
    const searchInput = document.getElementById('journalSearchInput');
    const clearBtn = document.getElementById('clearSearchBtn');
    const categoryPills = document.querySelectorAll('.category-pill');
    const articleCards = document.querySelectorAll('.article-card');
    const countDisplay = document.getElementById('articleCountDisplay');
    const noResults = document.getElementById('noResultsState');
    const resetBtn = document.getElementById('resetFiltersBtn');

    let currentCategory = 'all';
    let searchQuery = '';

    function filterArticles() {
      let visibleCount = 0;
      const query = searchQuery.trim().toLowerCase();

      articleCards.forEach(card => {
        const cat = card.getAttribute('data-category');
        const title = (card.getAttribute('data-title') || '').toLowerCase();
        const text = card.textContent.toLowerCase();

        const matchesCat = (currentCategory === 'all') || (cat === currentCategory);
        const matchesQuery = !query || title.includes(query) || text.includes(query);

        if (matchesCat && matchesQuery) {
          card.classList.remove('hidden');
          visibleCount++;
        } else {
          card.classList.add('hidden');
        }
      });

      if (countDisplay) {
        countDisplay.textContent = `Displaying ${visibleCount} Curated Exploration${visibleCount === 1 ? '' : 's'}`;
      }

      if (visibleCount === 0) {
        if (noResults) {
          noResults.classList.remove('hidden');
          noResults.classList.add('flex');
        }
      } else {
        if (noResults) {
          noResults.classList.add('hidden');
          noResults.classList.remove('flex');
        }
      }
    }

    if (searchInput) {
      searchInput.addEventListener('input', (e) => {
        searchQuery = e.target.value;
        if (searchQuery.length > 0) {
          clearBtn && clearBtn.classList.remove('hidden');
        } else {
          clearBtn && clearBtn.classList.add('hidden');
        }
        filterArticles();
      });
    }

    if (clearBtn) {
      clearBtn.addEventListener('click', () => {
        searchInput.value = '';
        searchQuery = '';
        clearBtn.classList.add('hidden');
        filterArticles();
        searchInput.focus();
      });
    }

    categoryPills.forEach(pill => {
      pill.addEventListener('click', () => {
        const targetCat = pill.getAttribute('data-cat');
        currentCategory = targetCat;

        categoryPills.forEach(p => {
          p.classList.remove('bg-primary', 'text-surface');
          p.classList.add('bg-surface-container', 'text-on-surface-variant');
        });

        pill.classList.remove('bg-surface-container', 'text-on-surface-variant');
        pill.classList.add('bg-primary', 'text-surface');

        filterArticles();
      });
    });

    if (resetBtn) {
      resetBtn.addEventListener('click', () => {
        if (searchInput) searchInput.value = '';
        searchQuery = '';
        clearBtn && clearBtn.classList.add('hidden');
        currentCategory = 'all';

        categoryPills.forEach(p => {
          if (p.getAttribute('data-cat') === 'all') {
            p.classList.add('bg-primary', 'text-surface');
            p.classList.remove('bg-surface-container', 'text-on-surface-variant');
          } else {
            p.classList.remove('bg-primary', 'text-surface');
            p.classList.add('bg-surface-container', 'text-on-surface-variant');
          }
        });

        filterArticles();
      });
    }
  })();
</script>

